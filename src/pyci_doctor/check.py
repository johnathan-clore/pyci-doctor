"""Compare a project's existing workflow with what pyci-doctor would generate today."""

from __future__ import annotations

import difflib
from dataclasses import dataclass
from enum import Enum
from pathlib import Path

from pyci_doctor.detect import detect
from pyci_doctor.render import HEADER_PREFIX, options_from_header, render_workflow

WORKFLOW_PATH = Path(".github") / "workflows" / "ci.yml"


class Status(Enum):
    UP_TO_DATE = "up to date"
    OUT_OF_DATE = "out of date"
    LINE_ENDINGS = "line endings differ"
    MISSING = "missing"
    NOT_GENERATED = "not generated by pyci-doctor"


@dataclass
class CheckResult:
    status: Status
    path: Path
    diff: str = ""

    @property
    def ok(self) -> bool:
        return self.status in (Status.UP_TO_DATE, Status.NOT_GENERATED)


def read_exact(path: Path) -> str:
    """Read text without converting line endings, so CRLF vs LF differences stay visible."""
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def check_workflow(project_dir: str | Path, strict: bool = False) -> CheckResult:
    """Raises DetectionError or RenderError if the project itself can't be inspected."""
    root = Path(project_dir)
    path = root / WORKFLOW_PATH

    if not path.is_file():
        return CheckResult(Status.MISSING, path)

    current = read_exact(path)
    first_line = current.split("\n", 1)[0].rstrip("\r")
    generated = first_line.startswith(HEADER_PREFIX)

    # A hand-written or hand-edited-and-header-removed workflow isn't ours to judge,
    # unless the user asks for strict checking.
    if not generated and not strict:
        return CheckResult(Status.NOT_GENERATED, path)

    # Regenerate with the same options the file was created with (recorded in its header).
    options = options_from_header(first_line) if generated else {}
    expected = render_workflow(detect(root), **options)

    if current == expected:
        return CheckResult(Status.UP_TO_DATE, path)

    if current.replace("\r\n", "\n") == expected:
        return CheckResult(Status.LINE_ENDINGS, path)

    diff = "".join(
        difflib.unified_diff(
            current.replace("\r\n", "\n").splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=f"{WORKFLOW_PATH.as_posix()} (current)",
            tofile=f"{WORKFLOW_PATH.as_posix()} (expected)",
        )
    )
    return CheckResult(Status.OUT_OF_DATE, path, diff)
