"""Turn a ProjectProfile into the text of a GitHub Actions workflow.

Pure function of its inputs: no file access, no clock, no randomness.
The same profile always produces byte-for-byte the same YAML.
"""

from __future__ import annotations

import re

from pyci_doctor import __version__
from pyci_doctor.detect import ProjectProfile

OPERATING_SYSTEMS = ("ubuntu-latest", "windows-latest", "macos-latest")
CHECKOUT_ACTION = "actions/checkout@v7"
SETUP_PYTHON_ACTION = "actions/setup-python@v7"
UPLOAD_ARTIFACT_ACTION = "actions/upload-artifact@v7"

# Pinned so a new ruff release can't turn CI red without any code change.
# tests/test_freshness.py (run weekly) reports when a newer version is out.
RUFF_VERSION = "0.17.5"

# The flaky job installs the same pyci-doctor version that generated the workflow,
# from a git tag, so a newer release can't change its behaviour unannounced.
PYCI_DOCTOR_SOURCE = f"git+https://github.com/johnathan-clore/pyci-doctor@v{__version__}"

# First line of every generated file. `check` uses it to tell generated files from hand-written
# ones, and to learn which init options were used, so it can regenerate with the same ones.
HEADER_PREFIX = "# Generated by pyci-doctor."
ALL_PYTHONS_FLAG = "--all-pythons"
FLAKY_RUNS_FLAG = "--flaky-runs"
COVERAGE_FLAG = "--coverage"


def header_line(all_pythons: bool = False, flaky_runs: int = 0, coverage: bool = False) -> str:
    command = "pyci-doctor init --force"
    if all_pythons:
        command += f" {ALL_PYTHONS_FLAG}"
    if flaky_runs:
        command += f" {FLAKY_RUNS_FLAG} {flaky_runs}"
    if coverage:
        command += f" {COVERAGE_FLAG}"
    return f"{HEADER_PREFIX} To regenerate: {command}"


def options_from_header(line: str) -> dict:
    """The reverse of header_line(): which init options produced this file."""
    match = re.search(rf"{FLAKY_RUNS_FLAG} (\d+)", line)
    return {
        "all_pythons": ALL_PYTHONS_FLAG in line,
        "flaky_runs": int(match.group(1)) if match else 0,
        "coverage": re.search(rf"{COVERAGE_FLAG}\b", line) is not None,
    }


class RenderError(Exception):
    """The profile doesn't contain enough to build a useful workflow."""


# --- Custom sections: where users add their own steps and jobs ---
#
# Every generated job ends with a marked section, and the workflow ends with one for extra jobs:
#
#       # >>> custom steps (test): pyci-doctor keeps anything between these lines
#       - name: Build the report
#         run: python -m evals.report
#       # <<< custom steps (test)
#
# `init --force` copies these sections into the new file unchanged, and `check` compares
# everything outside them, so a project can customise its CI and still be checked for drift.

CustomBlocks = dict[str, list[str]]  # section name ("test", "lint", "flaky" or "jobs") -> its lines

_MARKER_NAME = r"(?:steps \((?P<job>[\w-]+)\)|(?P<jobs>jobs))"
_START_RE = re.compile(rf"^\s*# >>> custom {_MARKER_NAME}:")
_END_RE = re.compile(rf"^\s*# <<< custom {_MARKER_NAME}\s*$")


def _section_label(name: str) -> str:
    return "custom jobs" if name == "jobs" else f"custom steps ({name})"


def _custom_section(name: str, custom: CustomBlocks) -> list[str]:
    indent = "  " if name == "jobs" else "      "
    label = _section_label(name)
    return [
        "",
        f"{indent}# >>> {label}: pyci-doctor keeps anything between these lines",
        *custom.get(name, []),
        f"{indent}# <<< {label}",
    ]


def extract_custom_blocks(workflow: str) -> CustomBlocks:
    """Read the custom sections back out of a workflow file."""
    blocks: CustomBlocks = {}
    current: str | None = None
    for number, line in enumerate(workflow.splitlines(), start=1):
        start, end = _START_RE.match(line), _END_RE.match(line)
        if start:
            if current is not None:
                raise RenderError(
                    f"Line {number}: a custom section starts before '{current}' has ended "
                    f"(is the '# <<< ...' end marker for '{current}' missing?)."
                )
            current = start.group("job") or "jobs"
            if current in blocks:
                raise RenderError(f"Line {number}: there are two custom sections for '{current}'.")
            blocks[current] = []
        elif end:
            name = end.group("job") or "jobs"
            if current != name:
                raise RenderError(f"Line {number}: end marker for '{name}' doesn't match an open section.")
            current = None
        elif current is not None:
            blocks[current].append(line)
    if current is not None:
        raise RenderError(f"The custom section for '{current}' is never closed.")
    return blocks


def matrix_pythons(profile: ProjectProfile, all_pythons: bool = False) -> list[str]:
    """Oldest and newest supported version by default; every supported version with all_pythons."""
    versions = profile.python_versions
    if not versions:
        raise RenderError("No supported Python versions; check requires-python in pyproject.toml.")
    if all_pythons or len(versions) <= 2:
        return list(versions)
    return [versions[0], versions[-1]]


def _with_package(profile: ProjectProfile, install_command: str, package: str) -> str:
    """Add one more package to the install command, in the project's own environment."""
    if profile.package_manager == "uv":
        return f"{install_command} && uv pip install {package}"
    if profile.package_manager == "poetry":
        return f"{install_command} && poetry run python -m pip install {package}"
    return f"{install_command} {package}" if install_command else f"python -m pip install {package}"


def _run_in_env(profile: ProjectProfile, module: str) -> str:
    """How to run a tool installed in the project's environment."""
    if profile.package_manager in ("uv", "poetry"):
        return f"{profile.package_manager} run {module}"
    return f"python -m {module}"


def _cache_lines(profile: ProjectProfile) -> list[str]:
    # setup-python's pip cache fails the job if it can't find the file it keys the cache on,
    # so only turn caching on when we know which file holds the dependencies.
    if profile.dependency_source == "pyproject":
        path = "pyproject.toml"
    elif profile.dependency_source == "requirements":
        path = "requirements*.txt"
    elif profile.dependency_source in ("uv.lock", "poetry.lock"):
        path = profile.dependency_source
    else:
        return []
    return [
        "          cache: pip",
        f"          cache-dependency-path: {path}",
    ]


def render_workflow(
    profile: ProjectProfile,
    all_pythons: bool = False,
    flaky_runs: int = 0,
    custom: CustomBlocks | None = None,
    coverage: bool = False,
) -> str:
    custom = custom or {}
    if coverage and profile.test_runner != "pytest":
        raise RenderError("--coverage needs a pytest project (it uses pytest-cov).")
    if profile.test_runner == "none" and not profile.has_ruff:
        raise RenderError("No tests or linter found, so CI would have nothing to run.")
    if flaky_runs and profile.test_runner != "pytest":
        raise RenderError("--flaky-runs needs a pytest project (it reads pytest's JUnit XML results).")
    if flaky_runs and flaky_runs < 2:
        raise RenderError("--flaky-runs must be at least 2.")

    lines = [
        header_line(all_pythons, flaky_runs, coverage),
        "name: CI",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  pull_request:",
        "  workflow_dispatch:",
        "",
        "permissions:",
        "  contents: read",
        "",
        "concurrency:",
        "  group: ${{ github.workflow }}-${{ github.ref }}",
        "  cancel-in-progress: true",
        "",
        "jobs:",
    ]

    if profile.test_runner != "none":
        pythons = ", ".join(f'"{v}"' for v in matrix_pythons(profile, all_pythons))
        lines += [
            "  test:",
            "    name: test (${{ matrix.os }}, py${{ matrix.python-version }})",
            "    runs-on: ${{ matrix.os }}",
            "    timeout-minutes: 15",
            "    strategy:",
            "      fail-fast: false",
            "      matrix:",
            f"        os: [{', '.join(OPERATING_SYSTEMS)}]",
            f"        python-version: [{pythons}]",
            "",
            "    steps:",
            "      - name: Check out code",
            f"        uses: {CHECKOUT_ACTION}",
            "",
            "      - name: Set up Python ${{ matrix.python-version }}",
            f"        uses: {SETUP_PYTHON_ACTION}",
            "        with:",
            "          python-version: ${{ matrix.python-version }}",
            *_cache_lines(profile),
            "",
        ]
        install_command, test_command = profile.install_command, profile.test_command
        if coverage:
            install_command = _with_package(profile, install_command, "pytest-cov")
            test_command += " --cov --cov-report=term"
        if install_command:
            lines += [
                "      - name: Install package and test tools",
                f"        run: {install_command}",
                "",
            ]
        lines += [
            "      - name: Run tests",
            f"        run: {test_command}",
        ]
        if coverage:
            lines += [
                "",
                "      - name: Show coverage on the run page",
                "        shell: bash  # also on Windows, so >> and $GITHUB_STEP_SUMMARY work the same everywhere",
                f'        run: {_run_in_env(profile, "coverage")} report --format=markdown >> "$GITHUB_STEP_SUMMARY"',
            ]
        lines += _custom_section("test", custom)

    if profile.has_ruff:
        if profile.test_runner != "none":
            lines.append("")
        newest = profile.python_versions[-1] if profile.python_versions else "3.14"
        lines += [
            "  lint:",
            "    runs-on: ubuntu-latest",
            "    timeout-minutes: 10",
            "    steps:",
            "      - name: Check out code",
            f"        uses: {CHECKOUT_ACTION}",
            "",
            "      - name: Set up Python",
            f"        uses: {SETUP_PYTHON_ACTION}",
            "        with:",
            f'          python-version: "{newest}"',
            "",
            "      - name: Install ruff",
            f"        run: python -m pip install ruff=={RUFF_VERSION}",
            "",
            "      - name: Lint",
            "        run: python -m ruff check .",
            *_custom_section("lint", custom),
        ]

    if flaky_runs:
        lines += ["", *_flaky_job(profile, flaky_runs), *_custom_section("flaky", custom)]

    lines += _custom_section("jobs", custom)

    # Never drop someone's custom steps silently, e.g. lint steps when ruff is no longer used.
    emitted = {"jobs"}
    if profile.test_runner != "none":
        emitted.add("test")
    if profile.has_ruff:
        emitted.add("lint")
    if flaky_runs:
        emitted.add("flaky")
    orphaned = sorted(name for name, body in custom.items() if name not in emitted and body)
    if orphaned:
        raise RenderError(
            f"The new workflow has no job for the custom steps in: {', '.join(orphaned)}. "
            "Move those steps to another custom section first, so they aren't lost."
        )

    return "\n".join(lines) + "\n"


def _flaky_command_option(profile: ProjectProfile) -> str:
    # pyci-doctor runs from the runner's Python; pytest must run inside the project's environment.
    if profile.package_manager in ("uv", "poetry"):
        return f' --command "{profile.package_manager} run pytest"'
    return ""


def _flaky_job(profile: ProjectProfile, runs: int) -> list[str]:
    newest = profile.python_versions[-1]
    lines = [
        "  flaky:",
        "    runs-on: ubuntu-latest",
        "    timeout-minutes: 30",
        "    steps:",
        "      - name: Check out code",
        f"        uses: {CHECKOUT_ACTION}",
        "",
        "      - name: Set up Python",
        f"        uses: {SETUP_PYTHON_ACTION}",
        "        with:",
        f'          python-version: "{newest}"',
        *_cache_lines(profile),
        "",
    ]
    if profile.install_command:
        lines += [
            "      - name: Install package and test tools",
            f"        run: {profile.install_command}",
            "",
        ]
    lines += [
        "      - name: Install pyci-doctor",
        # Skipped when the project already provides it (e.g. pyci-doctor testing itself).
        f'        run: python -c "import pyci_doctor" || python -m pip install "{PYCI_DOCTOR_SOURCE}"',
        "",
        f"      - name: Run tests {runs} times and report flaky tests",
        f"        run: python -m pyci_doctor flaky --runs {runs}{_flaky_command_option(profile)}",
        "",
        "      - name: Keep the results for inspection",
        "        if: always()",
        f"        uses: {UPLOAD_ARTIFACT_ACTION}",
        "        with:",
        "          name: flaky-results",
        "          path: flaky-results/",
    ]
    return lines
