"""Command-line entry point for pyci-doctor."""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path

from pyci_doctor import __version__
from pyci_doctor.check import WORKFLOW_PATH, Status, check_workflow
from pyci_doctor.detect import DetectionError, detect
from pyci_doctor.flaky import (
    FlakyError,
    classify,
    collect_result_files,
    format_report,
    parse_junit,
    run_repeatedly,
    to_dict,
)
from pyci_doctor.render import RenderError, render_workflow

# Exit codes for `check`, so a CI step or script can tell the cases apart.
EXIT_OK = 0
EXIT_PROBLEM_FOUND = 1
EXIT_CANNOT_CHECK = 2


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pyci-doctor",
        description="Generate GitHub Actions CI for a Python project and detect flaky tests.",
    )
    parser.add_argument(
        "--version", action="version", version=f"%(prog)s {__version__}"
    )
    subcommands = parser.add_subparsers(dest="command")

    detect_cmd = subcommands.add_parser("detect", help="Show what pyci-doctor finds in a project.")
    detect_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    detect_cmd.add_argument("--json", action="store_true", help="Print the result as JSON.")

    init_cmd = subcommands.add_parser("init", help="Write .github/workflows/ci.yml for a project.")
    init_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    init_cmd.add_argument(
        "--all-pythons",
        action="store_true",
        help="Test every supported Python version, not just the oldest and newest.",
    )
    init_cmd.add_argument(
        "--flaky-runs",
        type=int,
        default=0,
        metavar="N",
        help="Add a job that runs the tests N times and reports flaky tests (pytest only).",
    )
    init_cmd.add_argument("--force", action="store_true", help="Overwrite an existing ci.yml.")
    init_cmd.add_argument(
        "--stdout", action="store_true", help="Print the workflow instead of writing the file."
    )

    check_cmd = subcommands.add_parser(
        "check", help="Exit 1 if ci.yml differs from what `init` would generate now."
    )
    check_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    check_cmd.add_argument(
        "--strict",
        action="store_true",
        help="Also compare workflows that weren't generated by pyci-doctor.",
    )

    flaky_cmd = subcommands.add_parser(
        "flaky", help="Find flaky tests from repeated runs (JUnit XML results)."
    )
    flaky_cmd.add_argument(
        "results",
        nargs="*",
        help="JUnit XML files, or folders of them, one file per run.",
    )
    flaky_cmd.add_argument(
        "--runs",
        type=int,
        help="Run pytest this many times in the current folder instead of reading existing results.",
    )
    flaky_cmd.add_argument(
        "--out",
        default="flaky-results",
        help="Where --runs writes its result files (default: flaky-results).",
    )
    flaky_cmd.add_argument("--json", action="store_true", help="Print the result as JSON.")

    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.command == "detect":
        return _run_detect(args.path, as_json=args.json)
    if args.command == "check":
        return _run_check(args.path, strict=args.strict)
    if args.command == "flaky":
        return _run_flaky(args.results, runs=args.runs, out=args.out, as_json=args.json)
    if args.command == "init":
        return _run_init(
            args.path,
            all_pythons=args.all_pythons,
            flaky_runs=args.flaky_runs,
            force=args.force,
            to_stdout=args.stdout,
        )

    parser.print_help()
    return 0


def _run_detect(path: str, as_json: bool) -> int:
    try:
        profile = detect(path)
    except DetectionError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if as_json:
        print(json.dumps(profile.to_dict(), indent=2))
        return 0

    for key, value in profile.to_dict().items():
        if key == "warnings":
            continue
        if isinstance(value, list):
            value = ", ".join(value)
        print(f"{key:18} {value}")
    for warning in profile.warnings:
        print(f"warning: {warning}")
    return 0


def _run_init(path: str, all_pythons: bool, flaky_runs: int, force: bool, to_stdout: bool) -> int:
    try:
        profile = detect(path)
        workflow = render_workflow(profile, all_pythons=all_pythons, flaky_runs=flaky_runs)
    except (DetectionError, RenderError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    for warning in profile.warnings:
        print(f"warning: {warning}", file=sys.stderr)

    if to_stdout:
        sys.stdout.write(workflow)
        return 0

    target = Path(path) / WORKFLOW_PATH
    if target.exists() and not force:
        print(f"error: {target} already exists; use --force to overwrite it.", file=sys.stderr)
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" stops Windows from writing CRLF line endings, so the file is identical on every OS.
    target.write_text(workflow, encoding="utf-8", newline="\n")
    print(f"Wrote {target}")
    return 0


def _run_check(path: str, strict: bool) -> int:
    try:
        result = check_workflow(path, strict=strict)
    except (DetectionError, RenderError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    if result.status is Status.UP_TO_DATE:
        print(f"{result.path}: up to date")
    elif result.status is Status.NOT_GENERATED:
        print(f"{result.path}: not generated by pyci-doctor; skipped (use --strict to compare anyway)")
    elif result.status is Status.MISSING:
        print(f"{result.path}: missing; run: pyci-doctor init", file=sys.stderr)
    elif result.status is Status.LINE_ENDINGS:
        print(
            f"{result.path}: content matches but line endings differ (CRLF vs LF). "
            "Add '* text=auto eol=lf' to .gitattributes, or run: pyci-doctor init --force",
            file=sys.stderr,
        )
    else:
        print(f"{result.path}: out of date; run: pyci-doctor init --force", file=sys.stderr)
        sys.stdout.write(result.diff)

    return EXIT_OK if result.ok else EXIT_PROBLEM_FOUND


def _run_flaky(results: list[str], runs: int | None, out: str, as_json: bool) -> int:
    try:
        if runs is not None:
            if results:
                raise FlakyError("Give either result files or --runs, not both.")
            pytest_command = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"]
            files = run_repeatedly(
                pytest_command, runs, out, progress=lambda message: print(message, file=sys.stderr)
            )
        else:
            files = collect_result_files(results)
        all_runs = [parse_junit(f) for f in files]
    except FlakyError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    histories = classify(all_runs)
    if as_json:
        print(json.dumps(to_dict(histories, len(all_runs)), indent=2))
    else:
        sys.stdout.write(format_report(histories, len(all_runs)))

    problems = any(h.category in ("flaky", "stable-fail") for h in histories)
    return EXIT_PROBLEM_FOUND if problems else EXIT_OK
