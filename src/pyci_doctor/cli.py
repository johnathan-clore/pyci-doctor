"""Command-line entry point for pyci-doctor."""

from __future__ import annotations

import argparse
import difflib
import json
import os
import random
import shlex
import sys
from collections.abc import Sequence
from pathlib import Path

from pyci_doctor import __version__
from pyci_doctor import ai
from pyci_doctor.check import WORKFLOW_PATH, Status, check_workflow, read_exact
from pyci_doctor.detect import DetectionError, detect
from pyci_doctor.flaky import (
    FlakyError,
    classify,
    collect_result_files,
    format_report,
    github_annotations,
    markdown_summary,
    parse_junit,
    run_repeatedly,
    seeds_from_files,
    to_dict,
)
from pyci_doctor.render import HEADER_PREFIX, RenderError, extract_custom_blocks, render_workflow

# First line of a workflow written by `suggest --write`. It deliberately doesn't start with
# HEADER_PREFIX, so `check` treats the file as hand-maintained from then on.
AI_HEADER = "# Based on pyci-doctor output, with AI-suggested changes that passed its checks. Maintained by hand."

# Exit codes for `check`, so a CI step or script can tell the cases apart.
EXIT_OK = 0
EXIT_PROBLEM_FOUND = 1
EXIT_CANNOT_CHECK = 2


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pyci-doctor",
        description="Generate GitHub Actions CI for a Python project and detect flaky tests.",
    )
    parser.add_argument(
        "--version", action="version", version=f"%(prog)s {__version__}"
    )
    subcommands = parser.add_subparsers(dest="command")

    detect_cmd = subcommands.add_parser("detect", help="Show what pyci-doctor finds in a project.")
    detect_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    detect_cmd.add_argument("--json", action="store_true", help="Print the result as JSON.")

    init_cmd = subcommands.add_parser("init", help="Write .github/workflows/ci.yml for a project.")
    init_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    init_cmd.add_argument(
        "--all-pythons",
        action="store_true",
        help="Test every supported Python version, not just the oldest and newest.",
    )
    init_cmd.add_argument(
        "--flaky-runs",
        type=int,
        default=0,
        metavar="N",
        help="Add a job that runs the tests N times and reports flaky tests (pytest only).",
    )
    init_cmd.add_argument(
        "--coverage",
        action="store_true",
        help="Measure test coverage with pytest-cov and show it on the run page (pytest only).",
    )
    init_cmd.add_argument("--force", action="store_true", help="Overwrite an existing ci.yml.")
    init_cmd.add_argument(
        "--stdout", action="store_true", help="Print the workflow instead of writing the file."
    )

    check_cmd = subcommands.add_parser(
        "check", help="Exit 1 if ci.yml differs from what `init` would generate now."
    )
    check_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    check_cmd.add_argument(
        "--strict",
        action="store_true",
        help="Also compare workflows that weren't generated by pyci-doctor.",
    )

    flaky_cmd = subcommands.add_parser(
        "flaky", help="Find flaky tests from repeated runs (JUnit XML results)."
    )
    flaky_cmd.add_argument(
        "results",
        nargs="*",
        help="JUnit XML files, or folders of them, one file per run.",
    )
    flaky_cmd.add_argument(
        "--runs",
        type=int,
        help="Run pytest this many times in the current folder instead of reading existing results.",
    )
    flaky_cmd.add_argument(
        "--out",
        default="flaky-results",
        help="Where --runs writes its result files (default: flaky-results).",
    )
    flaky_cmd.add_argument(
        "--command",
        # Not dest="command": that name already holds which subcommand was chosen.
        dest="pytest_command",
        metavar="CMD",
        help='How to start pytest with --runs (default: "python -m pytest"), e.g. "uv run pytest".',
    )
    flaky_cmd.add_argument(
        "--seed",
        type=int,
        help="First shuffle seed for --runs; run i uses seed+i (default: random). Use it to replay a session.",
    )
    flaky_cmd.add_argument(
        "--no-shuffle", action="store_true", help="With --runs, keep the normal test order in every run."
    )
    flaky_cmd.add_argument(
        "--github",
        action="store_true",
        help="Print GitHub annotations and a run summary (automatic inside GitHub Actions).",
    )
    flaky_cmd.add_argument("--json", action="store_true", help="Print the result as JSON.")

    suggest_cmd = subcommands.add_parser(
        "suggest", help="Ask an AI model for workflow improvements and check them before use."
    )
    suggest_cmd.add_argument("path", nargs="?", default=".", help="Project folder (default: current folder).")
    suggest_cmd.add_argument(
        "--write", action="store_true", help="Write the suggestion to ci.yml if every check passes."
    )
    suggest_cmd.add_argument(
        "--model",
        default=os.environ.get("PYCI_DOCTOR_MODEL", ai.DEFAULT_MODEL),
        help=f"Model name (default: $PYCI_DOCTOR_MODEL or {ai.DEFAULT_MODEL}).",
    )
    suggest_cmd.add_argument("--json", action="store_true", help="Print the result as JSON.")

    return parser


def main(argv: Sequence[str] | None = None, client: ai.Client | None = None) -> int:
    """`client` lets tests supply a fake model; normally it's built from ANTHROPIC_API_KEY."""
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.command == "detect":
        return _run_detect(args.path, as_json=args.json)
    if args.command == "check":
        return _run_check(args.path, strict=args.strict)
    if args.command == "suggest":
        return _run_suggest(args.path, write=args.write, model=args.model, as_json=args.json, client=client)
    if args.command == "flaky":
        return _run_flaky(
            args.results,
            runs=args.runs,
            out=args.out,
            as_json=args.json,
            command=args.pytest_command,
            seed=None if args.no_shuffle else (args.seed if args.seed is not None else random.randrange(1, 100_000)),
            github=args.github or os.environ.get("GITHUB_ACTIONS") == "true",
        )
    if args.command == "init":
        return _run_init(
            args.path,
            all_pythons=args.all_pythons,
            flaky_runs=args.flaky_runs,
            coverage=args.coverage,
            force=args.force,
            to_stdout=args.stdout,
        )

    parser.print_help()
    return 0


def _run_detect(path: str, as_json: bool) -> int:
    try:
        profile = detect(path)
    except DetectionError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if as_json:
        print(json.dumps(profile.to_dict(), indent=2))
        return 0

    for key, value in profile.to_dict().items():
        if key == "warnings":
            continue
        if isinstance(value, list):
            value = ", ".join(value)
        print(f"{key:18} {value}")
    for warning in profile.warnings:
        print(f"warning: {warning}")
    return 0


def _run_init(
    path: str, all_pythons: bool, flaky_runs: int, force: bool, to_stdout: bool, coverage: bool = False
) -> int:
    target = Path(path) / WORKFLOW_PATH
    try:
        profile = detect(path)
        # Keep the custom sections of an existing workflow (only relevant with --force or --stdout).
        custom = extract_custom_blocks(read_exact(target).replace("\r\n", "\n")) if target.is_file() else {}
        workflow = render_workflow(
            profile, all_pythons=all_pythons, flaky_runs=flaky_runs, custom=custom, coverage=coverage
        )
    except (DetectionError, RenderError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    for warning in profile.warnings:
        print(f"warning: {warning}", file=sys.stderr)

    if to_stdout:
        sys.stdout.write(workflow)
        return 0

    if target.exists() and not force:
        print(f"error: {target} already exists; use --force to overwrite it.", file=sys.stderr)
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" stops Windows from writing CRLF line endings, so the file is identical on every OS.
    target.write_text(workflow, encoding="utf-8", newline="\n")
    print(f"Wrote {target}")
    return 0


def _run_check(path: str, strict: bool) -> int:
    try:
        result = check_workflow(path, strict=strict)
    except (DetectionError, RenderError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    if result.status is Status.UP_TO_DATE:
        print(f"{result.path}: up to date")
    elif result.status is Status.NOT_GENERATED:
        print(f"{result.path}: not generated by pyci-doctor; skipped (use --strict to compare anyway)")
    elif result.status is Status.MISSING:
        print(f"{result.path}: missing; run: pyci-doctor init", file=sys.stderr)
    elif result.status is Status.LINE_ENDINGS:
        print(
            f"{result.path}: content matches but line endings differ (CRLF vs LF). "
            "Add '* text=auto eol=lf' to .gitattributes, or run: pyci-doctor init --force",
            file=sys.stderr,
        )
    else:
        print(f"{result.path}: out of date; run: pyci-doctor init --force", file=sys.stderr)
        sys.stdout.write(result.diff)

    return EXIT_OK if result.ok else EXIT_PROBLEM_FOUND


def split_command(text: str, windows: bool = os.name == "nt") -> list[str]:
    """Split a command line into arguments, keeping Windows paths intact.

    shlex's normal (POSIX) mode treats backslashes as escapes, which turns
    C:\\Python314\\python.exe into C:Python314python.exe. On Windows, split in shlex's
    non-POSIX mode instead and remove the quotes it leaves around quoted arguments.
    """
    if not windows:
        return shlex.split(text)
    parts = shlex.split(text, posix=False)
    return [p[1:-1] if len(p) >= 2 and p[0] == p[-1] and p[0] in "\"'" else p for p in parts]


def _run_flaky(
    results: list[str],
    runs: int | None,
    out: str,
    as_json: bool,
    command: str | None = None,
    seed: int | None = None,
    github: bool = False,
) -> int:
    def progress(message: str) -> None:
        print(message, file=sys.stderr)

    try:
        if runs is not None:
            if results:
                raise FlakyError("Give either result files or --runs, not both.")
            base = split_command(command) if command else [sys.executable, "-m", "pytest"]
            if seed is not None:
                progress(f"shuffling test order; run i uses seed {seed}+i")
            files = run_repeatedly(
                [*base, "-q", "-p", "no:cacheprovider"], runs, out, progress=progress, seed=seed
            )
        else:
            files = collect_result_files(results)
        all_runs = [parse_junit(f) for f in files]
    except FlakyError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    histories = classify(all_runs)
    seeds = seeds_from_files(files)
    if as_json:
        print(json.dumps(to_dict(histories, len(all_runs), seeds), indent=2))
    else:
        sys.stdout.write(format_report(histories, len(all_runs), seeds))
        if github:
            for line in github_annotations(histories, len(all_runs)):
                print(line)

    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if github and summary_path:
        with open(summary_path, "a", encoding="utf-8") as summary:
            summary.write(markdown_summary(histories, len(all_runs), seeds))

    problems = any(h.category in ("flaky", "stable-fail") for h in histories)
    return EXIT_PROBLEM_FOUND if problems else EXIT_OK

def _run_suggest(path: str, write: bool, model: str, as_json: bool, client: ai.Client | None) -> int:

    target = Path(path) / WORKFLOW_PATH
    try:
        profile = detect(path)
        current = read_exact(target).replace("\r\n", "\n") if target.is_file() else render_workflow(profile)
        if client is None:
            api_key = os.environ.get("ANTHROPIC_API_KEY")
            if not api_key:
                raise ai.SuggestError("Set the ANTHROPIC_API_KEY environment variable to use suggest.")
            client = ai.anthropic_client(api_key, model=model)
        result = ai.suggest(profile, current, client)
    except (DetectionError, RenderError, ai.SuggestError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    if result.error:
        print(f"error: {result.error}", file=sys.stderr)
        return EXIT_CANNOT_CHECK

    diff = "".join(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            result.suggestion.workflow.splitlines(keepends=True),
            fromfile="ci.yml (current)",
            tofile="ci.yml (suggested)",
        )
    )

    if as_json:
        print(
            json.dumps(
                {
                    "accepted": result.accepted,
                    "unchanged": result.unchanged,
                    "changes": result.suggestion.changes,
                    "checks": [r.__dict__ for r in result.rules],
                    "diff": diff,
                },
                indent=2,
            )
        )
    else:
        _print_suggestion(result, diff)

    if result.unchanged:
        return EXIT_OK
    if not result.accepted:
        return EXIT_PROBLEM_FOUND

    if write:
        body = "".join(
            line
            for line in result.suggestion.workflow.splitlines(keepends=True)
            if not line.startswith(HEADER_PREFIX)  # a kept generator header would confuse `check`
        )
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(f"{AI_HEADER}\n{body}", encoding="utf-8", newline="\n")
        print(f"Wrote {target}", file=sys.stderr)
    return EXIT_OK


def _print_suggestion(result: ai.SuggestResult, diff: str) -> None:
    # Plain ASCII labels: the Windows PowerShell 5.1 console can't print symbols like a check mark.
    if result.unchanged:
        print("The model suggested no changes.")
        return
    print("Suggested changes:")
    for change in result.suggestion.changes:
        print(f"  - {change.get('summary', '')}: {change.get('reason', '')}")
    print()
    print("Checks:")
    for rule in result.rules:
        label = "PASS" if rule.passed else ("WARN" if rule.severity == "warning" else "FAIL")
        print(f"  {label}  {rule.rule:28} {rule.message}")
    print()
    sys.stdout.write(diff)
    print()
    failed = [r for r in result.rules if not r.passed and r.severity == "error"]
    if failed:
        print(f"Rejected: {len(failed)} check(s) failed. Nothing was written.")
    else:
        print("Accepted: every check passed. Use --write to save it, or copy what you want from the diff.")
