TESTS = Path(__file__).parent
FIXTURES = TESTS / "fixtures"
GOLDEN = TESTS / "golden"
REPO_ROOT = TESTS.parent

RENDERABLE_FIXTURES = ["src_pytest", "flat_requirements", "unittest_only", "config_only_pyproject"]


def read_exact(path: Path) -> str:
    # newline="" turns off Python's line-ending translation, so a CRLF file stays CRLF
    # and the comparison really is byte-for-byte.
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def make_profile(**overrides) -> ProjectProfile:
    """A hand-built profile, so generator tests don't depend on the detector."""
    values = dict(
        name="demo",
        layout="src",
        dependency_source="pyproject",
        install_command='python -m pip install -e ".[dev]"',
        test_runner="pytest",
        test_command="python -m pytest -v",
        python_versions=["3.11", "3.12", "3.13", "3.14"],
        has_ruff=False,
        has_coverage=False,
    )
    values.update(overrides)
    return ProjectProfile(**values)


def parse(workflow: str) -> dict:
    data = yaml.safe_load(workflow)
    # PyYAML follows YAML 1.1, where a bare `on` key means the boolean True.
    # GitHub reads it as the string "on". Normalise so tests can use data["on"].
    if True in data:
        data["on"] = data.pop(True)
    return data


# --- Golden files: the full expected output for each fake project ---


@pytest.mark.parametrize("fixture", RENDERABLE_FIXTURES)
def test_output_matches_golden_file(fixture, request):
    workflow = render_workflow(detect(FIXTURES / fixture))
    golden = GOLDEN / f"{fixture}.yml"

    if request.config.getoption("--update-golden"):
        golden.parent.mkdir(exist_ok=True)
        golden.write_text(workflow, encoding="utf-8", newline="\n")
        pytest.skip(f"updated {golden.name}")

    assert golden.exists(), f"{golden} missing; run: python -m pytest --update-golden"
    assert read_exact(golden) == workflow


def test_golden_files_have_unix_line_endings():
    # If this fails on Windows, .gitattributes isn't being applied to the checkout.
    for golden in GOLDEN.glob("*.yml"):
        assert b"\r\n" not in golden.read_bytes(), golden.name


def test_repo_own_workflow_is_up_to_date():
    # pyci-doctor's own CI is generated by pyci-doctor. If someone edits ci.yml by hand
    # or changes the generator without regenerating, this fails.
    from pyci_doctor.render import options_from_header

    actual = read_exact(REPO_ROOT / ".github" / "workflows" / "ci.yml")
    options = options_from_header(actual.split("\n", 1)[0])  # regenerate with the same init options
    expected = render_workflow(detect(REPO_ROOT), **options)
    assert actual == expected, "Run the init command shown on the first line of ci.yml"


# --- Properties every generated workflow must have ---


@pytest.mark.parametrize("fixture", RENDERABLE_FIXTURES)
def test_output_is_valid_yaml_with_the_expected_shape(fixture):
    profile = detect(FIXTURES / fixture)
    data = parse(render_workflow(profile))

    assert set(data["on"]) == {"push", "pull_request", "workflow_dispatch"}
    assert data["permissions"] == {"contents": "read"}

    test_job = data["jobs"]["test"]
    assert test_job["strategy"]["fail-fast"] is False
    assert test_job["strategy"]["matrix"]["os"] == list(OPERATING_SYSTEMS)
    versions = test_job["strategy"]["matrix"]["python-version"]
    assert all(isinstance(v, str) for v in versions), "versions must stay strings, e.g. '3.10' not 3.1"

    commands = [step.get("run") for step in test_job["steps"]]
    assert commands[-1] == profile.test_command
    if profile.install_command:
        assert profile.install_command in commands


