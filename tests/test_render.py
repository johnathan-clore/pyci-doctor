def test_flaky_job_runs_the_suite_n_times_and_keeps_results():
    data = parse(render_workflow(make_profile(), flaky_runs=7))
    steps = data["jobs"]["flaky"]["steps"]
    commands = [s.get("run", "") for s in steps]
    assert "python -m pyci_doctor flaky --runs 7" in commands
    upload = steps[-1]
    assert upload["if"] == "always()", "results must be uploaded even when flaky tests fail the job"
    assert upload["with"]["path"] == "flaky-results/"


