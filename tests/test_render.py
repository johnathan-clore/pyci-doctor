# --- The generated commands actually work ---


def test_generated_unittest_command_finds_the_tests():
    # Runs on every Python in the CI matrix, so a version where discovery finds 0 tests is caught.
    project = FIXTURES / "unittest_only"
    command = detect(project).test_command.split()
    assert command[:2] == ["python", "-m"]
    result = subprocess.run(
        [sys.executable, *command[1:]],
        cwd=project,
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, result.stderr
    assert "Ran 1 test" in result.stderr


# --- The `init` command ---


def test_init_writes_the_workflow_with_unix_line_endings(tmp_path, capsys):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "x"\nversion = "1"\n[tool.pytest.ini_options]\n')
    assert main(["init", str(tmp_path)]) == 0

    target = tmp_path / ".github" / "workflows" / "ci.yml"
    raw = target.read_bytes()
    assert b"\r\n" not in raw, "Windows line endings leaked into the generated file"
    assert raw.decode("utf-8") == render_workflow(detect(tmp_path))
    assert "Wrote" in capsys.readouterr().out


def test_init_refuses_to_overwrite_without_force(tmp_path, capsys):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "x"\nversion = "1"\n[tool.pytest.ini_options]\n')
    target = tmp_path / ".github" / "workflows" / "ci.yml"
    target.parent.mkdir(parents=True)
    target.write_text("my hand-written CI\n")

    assert main(["init", str(tmp_path)]) == 1
    assert "use --force" in capsys.readouterr().err
    assert target.read_text() == "my hand-written CI\n"

    assert main(["init", str(tmp_path), "--force"]) == 0
    assert target.read_text().startswith("# Generated by pyci-doctor")


def test_init_stdout_prints_and_writes_nothing(tmp_path, capsys):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "x"\nversion = "1"\n[tool.pytest.ini_options]\n')
    assert main(["init", str(tmp_path), "--stdout"]) == 0
    assert capsys.readouterr().out.startswith("# Generated by pyci-doctor")
    assert not (tmp_path / ".github").exists()


def test_init_with_nothing_to_run_fails_cleanly(capsys):
    assert main(["init", str(FIXTURES / "no_tests"), "--stdout"]) == 1
    captured = capsys.readouterr()
    assert captured.out == ""
    assert "nothing to run" in captured.err


